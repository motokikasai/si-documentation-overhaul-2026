#!/usr/bin/env python3
"""
Collect every translatable string the child theme carries into one .pot.

    python3 build/make-pot.py            # -> wp/blocksy-child/languages/si.pot

Why not `wp i18n make-pot`: that needs WP-CLI, which on this machine only runs
inside Local's "Open Site Shell" — so the .pot could not be regenerated from the
repo, where the strings actually live. This scans the PHP of BOTH kits (the
/people/ one and the Articles one) plus the JS string tables, and writes a single
`si` domain .pot, because they ship as one theme.

The .pot is what WPML's String Translation scan and any .po editor read. It is a
build artefact: regenerate it whenever a string changes, never hand-edit it.
"""
import os, re, sys, datetime, collections

HERE = os.path.dirname(os.path.abspath(__file__))
REBUILD = os.path.abspath(os.path.join(HERE, '../..'))
# One .pot for the whole child theme, written into BOTH kits: the two packagers
# can run in either order and ship the same complete file.
OUTS = [
    os.path.join(REBUILD, 'articles/wp/blocksy-child/languages/si.pot'),
    os.path.join(REBUILD, 'people/wp/blocksy-child/languages/si.pot'),
]

SOURCES = [
    ('people/wp/blocksy-child', ('inc', 'template-parts')),
    ('articles/wp/blocksy-child', ('inc', 'template-parts')),
]

# __( 'x', 'si' ) · _e · esc_html__ · esc_attr_e · _x( 'x', 'ctx', 'si' )
#  · _n( 'one', 'many', $n, 'si' ) · esc_html_x …
# Only the gettext family — NOT bare esc_html()/esc_attr(), which escape a
# string without translating it and would drag in every array key on the page.
CALL = re.compile(r"""
    \b(?P<fn>__|_e|_x|_n|_nx|esc_(?:html|attr)(?:__|_e|_x))\s*\(\s*
    (?P<args>(?:'(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*"|[^()]|\([^()]*\))*?)
    \s*\)""", re.X)
STR = re.compile(r"""(?P<q>['"])(?P<s>(?:\\.|(?!(?P=q))[^\\])*)(?P=q)""")
COMMENT = re.compile(r"/\*\s*translators:\s*(.*?)\s*\*/|//\s*translators:\s*(.*)", re.S | re.I)


def unquote(raw, quote):
    s = raw.replace("\\" + quote, quote).replace('\\\\', '\\')
    return s.replace('\\n', '\n').replace('\\t', '\t')


def scan(path, rel):
    text = open(path, encoding='utf-8').read()
    lines = text[:0]
    found = []
    for m in CALL.finditer(text):
        fn = m.group('fn')
        args = [(mm.group('s'), mm.group('q')) for mm in STR.finditer(m.group('args'))]
        if not args:
            continue
        # the text domain is always the last argument; anything else is not ours
        if unquote(*args[-1]) != 'si':
            continue
        line = text.count('\n', 0, m.start()) + 1
        # the translator comment immediately above the call, if any
        head = text[max(0, m.start() - 400):m.start()]
        note = None
        cm = list(COMMENT.finditer(head))
        if cm and head[cm[-1].end():].strip().startswith(('printf', 'sprintf', '$', 'echo', '')) :
            note = (cm[-1].group(1) or cm[-1].group(2) or '').strip()
            note = re.sub(r'\s*\*\s*', ' ', note).strip()
        entry = {'file': rel, 'line': line, 'note': note, 'ctx': None,
                 'msgid': unquote(*args[0]), 'plural': None}
        if fn.endswith('_x') or fn == '_x':
            if len(args) > 1:
                entry['ctx'] = unquote(*args[1])
        if fn in ('_n', '_nx') or fn.endswith('_n'):
            if len(args) > 1:
                entry['plural'] = unquote(*args[1])
        found.append(entry)
    return found


def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


class _Collector:
    """Lets the writer below stay a single `f.write(...)` sequence while the
    result goes to more than one file."""

    def __init__(self, sink):
        self.sink = sink

    def write(self, chunk):
        self.sink.append(chunk)


def main():
    entries = collections.OrderedDict()
    for base, dirs in SOURCES:
        root = os.path.join(REBUILD, base)
        if not os.path.isdir(root):
            continue
        for d in dirs:
            for dirpath, _, names in os.walk(os.path.join(root, d)):
                for name in sorted(names):
                    if not name.endswith('.php'):
                        continue
                    path = os.path.join(dirpath, name)
                    rel = os.path.relpath(path, root)
                    for e in scan(path, rel):
                        key = (e['ctx'], e['msgid'], e['plural'])
                        entries.setdefault(key, {'refs': [], 'note': None, **e})['refs'].append(
                            '%s:%d' % (e['file'], e['line']))
                        if e['note'] and not entries[key]['note']:
                            entries[key]['note'] = e['note']

    body = []
    f = _Collector(body)
    if True:
        f.write('# Blocksy Child — Schiller Institute (text domain: si)\n')
        f.write('# Generated by articles/build/make-pot.py — do not hand-edit.\n')
        f.write('msgid ""\nmsgstr ""\n'
                '"Project-Id-Version: blocksy-child\\n"\n'
                '"MIME-Version: 1.0\\n"\n'
                '"Content-Type: text/plain; charset=UTF-8\\n"\n'
                '"Content-Transfer-Encoding: 8bit\\n"\n'
                '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"\n'
                '"POT-Creation-Date: %s\\n"\n'
                '"X-Domain: si\\n"\n\n' % datetime.datetime.utcnow().strftime('%Y-%m-%d %H:%M+0000'))
        for (ctx, msgid, plural), e in entries.items():
            if e['note']:
                f.write('#. translators: %s\n' % e['note'])
            for ref in e['refs']:
                f.write('#: %s\n' % ref)
            if '%' in msgid or (plural and '%' in plural):
                f.write('#, php-format\n')
            if ctx:
                f.write('msgctxt "%s"\n' % esc(ctx))
            f.write('msgid "%s"\n' % esc(msgid))
            if plural:
                f.write('msgid_plural "%s"\nmsgstr[0] ""\nmsgstr[1] ""\n\n' % esc(plural))
            else:
                f.write('msgstr ""\n\n')
    text = ''.join(body)
    for out in OUTS:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, 'w', encoding='utf-8') as fh:
            fh.write(text)
        print('%d strings -> %s' % (len(entries), os.path.relpath(out, REBUILD)))


if __name__ == '__main__':
    main()
