#!/usr/bin/env bash
# Assemble the deployable child-theme additions for Pages (the Pavilion).
#   pages/build/package-wp.sh <dest>     e.g. <dest> = .../wp-content/themes/blocksy-child
#
# One source of truth: the CSS the prototype runs IS what ships.
#   pages-shared.css  → assets/pages/css/pages-prose.css, cut at the PROTO marker
#                       (the same marker people/build/audit-literals.py audits up to)
#   page-pavilion.css → as it is
#   page-pavilion-wp.js, not page-pavilion.js: WordPress renders the page on the
#                       server; the module only marks the section being read
#   img/band-earth-disc.webp → the band's default picture
#
# This ADDS to an existing blocksy-child: it never overwrites functions.php, only
# appends the one require line (and people/build/package-wp.sh keeps it since
# 2026-09-29).
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
dest="${1:?usage: package-wp.sh <blocksy-child dir>}"
[ -f "$dest/functions.php" ] || { echo "not a child theme: $dest" >&2; exit 1; }
marker='/* ---- 3 · PROTO'

mkdir -p "$dest/inc" "$dest/template-parts/pages" "$dest/assets/pages/css" "$dest/assets/pages/js" "$dest/assets/pages/img"

cp "$here"/wp/blocksy-child/inc/pages.php "$here"/wp/blocksy-child/inc/page-pavilion.php "$dest/inc/"
cp "$here"/wp/blocksy-child/template-parts/pages/pavilion.php "$dest/template-parts/pages/"

grep -qF "$marker" "$here/templates/css/pages-shared.css" || { echo "PROTO marker missing from pages-shared.css" >&2; exit 1; }
{
	echo "/* pages-prose.css — generated by pages/build/package-wp.sh from pages/templates/css/pages-shared.css,"
	echo "   parts 1–2 only (the prose container and the pattern kit). Edit the source, not this. */"
	awk -v m="$marker" 'index($0, m) == 1 { exit } { print }' "$here/templates/css/pages-shared.css"
} > "$dest/assets/pages/css/pages-prose.css"
cp "$here/templates/css/page-pavilion.css" "$dest/assets/pages/css/"
cp "$here/templates/js/page-pavilion-wp.js" "$dest/assets/pages/js/"
cp "$here/templates/img/band-earth-disc.webp" "$dest/assets/pages/img/"

# one require line in functions.php, added once
if ! grep -q "inc/pages.php" "$dest/functions.php"; then
	printf "\nrequire_once __DIR__ . '/inc/pages.php';   // every Page: the Pavilion\n" >> "$dest/functions.php"
	echo "added the require line to functions.php"
fi

# A shipped file must never *load* anything from the prototype layer. Prose that
# names a prototype file is fine (the porting seam is the point of those
# comments), so the test looks for code — an import, an @import, a url() — not words.
if grep -rlnE "@import|url\([^)]*(blocksy-shim|proto)|from '\./(pages-core|pavilion-motif|search-core)\.js'|import\(" \
		"$dest/assets/pages" "$dest/template-parts/pages" "$dest/inc/page-pavilion.php" 2>/dev/null; then
	echo "prototype-only reference found in shipped files" >&2; exit 1
fi
echo "packaged into $dest"
